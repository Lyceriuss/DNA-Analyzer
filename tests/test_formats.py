"""Raw file formats (genome/formats.py), on small made-up files: no real genotypes."""
import gzip
import os
import tempfile
import unittest
import zipfile

from genome import formats
from genome.loader import iter_calls, person_label

ANCESTRY = ("#AncestryDNA raw data download\n#\n"
            "rsid\tchromosome\tposition\tallele1\tallele2\n"
            "rs1\t1\t101\tA\tG\n"
            "rs2\t1\t102\t0\t0\n"
            "rs3\t23\t103\tT\tT\n"
            "rs4\t25\t104\tC\tT\n"
            "rs5\t26\t105\tA\tA\n"
            "rs6\t2\t\t106\tG\tG\n")  # extra tab, as some exports have
MYHERITAGE = ('# MyHeritage DNA raw data.\n"RSID","CHROMOSOME","POSITION","RESULT"\n'
              '"rs1","1","101","AG"\n"rs2","1","102","--"\n"rs3","X","103","TT"\n')
TWENTYTHREE = ("# This data file generated by 23andMe\n# rsid\tchromosome\tposition\tgenotype\n"
               "rs1\t1\t101\tAG\nrs2\t1\t102\t--\nrs3\tX\t103\tT\n")
EXPECTED = [("rs1", "1", 101, "AG"), ("rs2", "1", 102, "--"), ("rs3", "X", 103, "TT")]


class Formats(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()

    def tearDown(self):
        self.dir.cleanup()

    def file(self, name, text, how="plain"):
        p = os.path.join(self.dir.name, name)
        if how == "zip":
            with zipfile.ZipFile(p, "w") as z:
                z.writestr("AncestryDNA.txt", text)
        elif how == "gz":
            with gzip.open(p, "wt") as f:
                f.write(text)
        else:
            with open(p, "w") as f:
                f.write(text)
        return p

    def test_ancestry(self):
        p = self.file("a.txt", ANCESTRY)
        self.assertEqual(formats.detect(p), "ancestry")
        self.assertEqual(list(formats.rows(p)), [
            ("rs1", "1", 101, "AG"), ("rs2", "1", 102, "--"), ("rs3", "X", 103, "TT"),
            ("rs4", "X", 104, "CT"), ("rs5", "MT", 105, "AA"), ("rs6", "2", 106, "GG")])

    def test_ancestry_zipped_and_gzipped(self):
        plain = list(formats.rows(self.file("a.txt", ANCESTRY)))
        self.assertEqual(list(formats.rows(self.file("a.zip", ANCESTRY, "zip"))), plain)
        self.assertEqual(list(formats.rows(self.file("a.txt.gz", ANCESTRY, "gz"))), plain)

    def test_myheritage(self):
        p = self.file("m.csv", MYHERITAGE)
        self.assertEqual(formats.detect(p), "myheritage")
        self.assertEqual(list(formats.rows(p)), EXPECTED)

    def test_23andme(self):
        p = self.file("t.txt", TWENTYTHREE)
        self.assertEqual(formats.detect(p), "23andme")
        self.assertEqual(list(formats.rows(p))[:2], EXPECTED[:2])
        self.assertEqual(list(formats.rows(p))[2], ("rs3", "X", 103, "T"))  # a man's X, one letter

    def test_loader_reads_every_format_alike(self):
        a = list(iter_calls(self.file("a.txt", ANCESTRY), rsids={"rs1", "rs2"}, confidence=None))
        m = list(iter_calls(self.file("m.csv", MYHERITAGE), rsids={"rs1", "rs2"}, confidence=None))
        self.assertEqual(a, m)
        self.assertEqual(a[0], ("rs1", "1", 101, "AG", "measured"))

    def test_not_a_dna_file(self):
        with self.assertRaises(SystemExit):
            formats.detect(self.file("x.txt", "hello world\n"))

    def test_person_label(self):
        self.assertEqual(person_label("data/input/MyHeritage_raw_dna_data_XY.csv"), "XY")
        self.assertEqual(person_label("x/MyHeritage_raw_dna_data_XY.imputed.csv"), "XY")
        self.assertEqual(person_label("data/input/XX.txt.zip"), "XX")
        self.assertEqual(person_label("data/input/AncestryDNA.txt"), "AncestryDNA")


if __name__ == "__main__":
    unittest.main()
